def seed_case(db, *, n_hpf: int):
    case_id = uuid.uuid4()
    db.add(Case(id=case_id, created_by="contract_test"))
    db.add(Slide(id=uuid.uuid4(), case_id=case_id, gcs_uri_original="gs://raw/s.svs", mpp_x=0.25, mpp_y=0.25,
                 width_px=40000, height_px=40000))
    db.add(StageExecution(id=uuid.uuid4(), case_id=case_id, stage="mitosis", attempt=1, status="awaiting_review",
                          model_versions={"kongnet_det_midog_1": "v2"}, config_hash="c" * 64))
    db.flush()
    exec_id = db.scalars(select(StageExecution.id).where(StageExecution.case_id == case_id)).one()
    for seq in range(1, n_hpf + 1):
        centre = [1000.0 * seq, 1000.0]
        db.add(HpfSite(case_id=case_id, seq=seq, center_um=centre, radius_um=250.0,
                       mitotic_count=0, tissue_coverage=0.95, tumor_fraction=0.8))
        db.add(Hotspot(id=f"hs_{seq:02d}", case_id=case_id, stage_execution_id=exec_id, center_um=centre, hpf_diameter_um=500.0,
                       window_um=600.0, rank=seq, source="model", excluded=False,
                       polygon_um=[[centre[0] - 300, 700.0], [centre[0] + 300, 700.0], [centre[0] + 300, 1300.0],
                                   [centre[0] - 300, 1300.0], [centre[0] - 300, 700.0]]))
    vlm = {"verdict": "EQUIVOCAL", "criteria": {"membrane_absent": True, "condensed_chromosome_projections": False,
                                               "phase": "none", "neoplastic_cell": True},
           "mimic": "pyknotic_nucleus", "rationale": "dense round body", "rule_override": False}
    db.add_all([
        Detection(id="m_0001", case_id=case_id, hotspot_id="hs_01", centroid_um=[1000.0, 1000.0], p_a=0.91,
                  final_decision="mitosis", decision_path="A", record_ids=["r1"]),
        Detection(id="m_0002", case_id=case_id, hotspot_id="hs_01", centroid_um=[1100.0, 1000.0], p_a=0.81, vlm=vlm,
                  final_decision="equivocal", decision_path="A", record_ids=["r2", "r3"]),
        Detection(id="m_user_0a1b2c3d", case_id=case_id, centroid_um=[2000.0, 1000.0], p_a=None,
                  final_decision="mitosis", decision_path="human", review_label="mitosis"),
    ])
    db.commit()
    return str(case_id)


@pytest.mark.parametrize("n_hpf", [10, 3, 0])
def test_get_validates_against_the_contract(session_factory, n_hpf):
    db = session_factory()
    case_id = seed_case(db, n_hpf=n_hpf)
    db.close()
    res = TestClient(app).get(f"/api/v1/stages/mitosis/{case_id}", headers={"X-Test-Role": "pathologist"})
    assert res.status_code == 200, res.text
    stage = MitosisStageV6.model_validate_json(res.text)
    assert stage.summary.hpf_target == 10 and all(c.hpf_seq is None or c.hpf_seq >= 1 for c in stage.candidates)
    assert [h.hotspot_id for h in stage.hpfs] == [f"hs_{seq:02d}" for seq in range(1, n_hpf + 1)]
    assert all(h.frame_um is not None and len(h.frame_um) == 5 for h in stage.hpfs)
    if n_hpf == 0:
        assert stage.summary.mitotic_score is None and stage.summary.n_hpf == 0 and stage.summary.flags == ["hpf_count_lt_10"]
    elif n_hpf == 10:
        assert stage.summary.flags == [] and stage.summary.count_total == 2 and stage.summary.n_equivocal == 1


def test_counted_column_equals_the_python_mirror_for_every_combination(session_factory):
    db = session_factory()
    case_id = uuid.uuid4()
    db.add(Case(id=case_id, created_by="contract_test"))
    combos = list(itertools.product([None, "mitosis", "not_mitosis"], ["mitosis", "not_mitosis", "equivocal"], [None, True, False]))
    for i, (review_label, final_decision, in_tumor) in enumerate(combos):
        db.add(Detection(id=f"m_{i:04d}", case_id=case_id, centroid_um=[float(i), 0.0], p_a=0.9, final_decision=final_decision,
                         decision_path="A", review_label=review_label, in_tumor=in_tumor))
    db.commit()
    for i, combo in enumerate(combos):
        assert bool(db.get(Detection, (f"m_{i:04d}", case_id)).counted) is is_counted(*combo), combo
    db.close()


