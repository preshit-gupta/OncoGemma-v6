def test_score_thresholds_are_compared_only_in_pipeline_scoring():
    """SPEC-06 AC10: no backend file other than pipeline/scoring.py reads the mitotic score thresholds
    (pipeline_config.py declares them; tests are excluded)."""
    allowed = {BACKEND / "pipeline" / "scoring.py", BACKEND / "app" / "core" / "pipeline_config.py"}
    pattern = re.compile(r"\.score[23]_min\b")  # the mitotic thresholds, not the tubule *_min_percent
    offenders = [
        str(path.relative_to(REPO)) for path in BACKEND.rglob("*.py")
        if "tests" not in path.relative_to(BACKEND).parts and path not in allowed
        and pattern.search(path.read_text(encoding="utf-8"))
    ]
    assert offenders == []


