class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)


class Criteria(Strict):
    membrane_absent: bool
    condensed_chromosome_projections: bool
    phase: Literal["prometaphase", "metaphase", "anaphase", "telophase", "atypical", "none"]
    neoplastic_cell: bool


class VlmVerdict(Strict):
    verdict: Literal["MITOTIC_FIGURE", "NOT_MITOTIC_FIGURE", "EQUIVOCAL"]
    criteria: Criteria
    mimic: Literal["none", "apoptotic_body", "pyknotic_nucleus", "hyperchromatic_interphase", "lymphocyte",
                   "prophase", "crush", "other"]
    rationale: str
    rule_override: bool


Number = float | int


class MitosisDescription(Strict):
    chromatin: Literal["condensed_clumps", "band_or_plate", "two_separated_masses", "fine_granular", "smooth_dense",
                       "beaded_fragments", "not_assessable"]
    nuclear_membrane: Literal["not_visible", "partly_visible", "intact", "not_assessable"]
    outline: Literal["hairy_projections", "smooth", "not_assessable"]
    cytoplasm: Literal["clear_halo", "eosinophilic", "none_visible", "not_assessable"]
    relative_size: Literal["larger", "similar", "smaller", "not_assessable"]
    setting: Literal["tumour_cells", "stroma", "inflammatory", "necrosis", "lumen", "not_assessable"]
    summary: str


class Candidate(Strict):
    id: str
    hotspot_id: Optional[str]
    centroid_um: tuple[Number, Number]
    p_a: Optional[Number]
    p_b: Optional[Number]
    vlm: Optional[VlmVerdict]
    in_tumor: Optional[bool]  # null only in an eval tumour-gate ablation run
    final_decision: Literal["mitosis", "not_mitosis", "equivocal"]
    decision_path: Literal["A", "AB", "ABC", "human"]
    review_label: Optional[Literal["mitosis", "not_mitosis"]]
    counted: bool
    crop_url: str
    context_url: str
    # WP-6.5: the fixture gains these in WP-7.10; the API must always send them (asserted below).
    hpf_seq: Optional[int] = None
    # WP-7.9: morphology description, never a decision.
    description: Optional[MitosisDescription]
    description_status: Literal["ok", "unavailable", "not_requested"]


class Hpf(Strict):
    seq: int
    center_um: tuple[Number, Number]
    radius_um: Number
    count: int
    tissue_coverage: Number
    tumor_fraction: Number
    hotspot_id: Optional[str] = None
    frame_um: Optional[list[tuple[Number, Number]]] = None


class MitosisSummary(Strict):
    count_total: int
    n_hpf: int
    area_mm2: Number
    per_mm2: Number
    mitotic_score: Optional[Literal[1, 2, 3]]
    n_equivocal: int
    flags: list[Literal["hpf_count_lt_10"]]
    hpf_target: Optional[int] = None


class SlideGeom(Strict):
    width_px: int
    height_px: int
    mpp_x: Number
    mpp_y: Number


class Provenance(Strict):
    stage: str
    model_versions: dict[str, str]
    config_hash: str
    run_mode: Literal["clinical", "eval", "shadow"]


class MitosisStageV6(Strict):
    case_id: str
    stage_execution_id: str
    status: Literal["queued", "running", "awaiting_review", "confirmed", "failed"]
    slide: SlideGeom
    candidates: list[Candidate]
    hpfs: list[Hpf]
    summary: MitosisSummary
    provenance: Provenance


