def test_0016_maps_v5_rows_and_drops_the_v5_columns(tmp_path):
    engine = create_engine(f"sqlite:///{tmp_path / 'oncogemma.db'}")
    run(engine, command.upgrade, "0015_hotspot_v6_fields")
    case_id = str(uuid.uuid4())
    with engine.begin() as conn:
        conn.execute(text("INSERT INTO cases (id, created_by, status, created_at) VALUES (:id, 'v5', 'open', CURRENT_TIMESTAMP)"), {"id": case_id})
        for row in V5_ROWS:
            conn.execute(text(
                "INSERT INTO detections (id, case_id, centroid_um, det_conf, label, label_source, medgemma_verdict) "
                "VALUES (:id, :case_id, '[1.0, 2.0]', :det_conf, :label, :source, 'CONFIRMED')"
            ), {"id": row[0], "case_id": case_id, "det_conf": row[1], "label": row[2], "source": row[3]})
    run(engine, command.upgrade, "0016_detections_v6")

    with engine.connect() as conn:
        got = {r.id: r for r in conn.execute(text(
            "SELECT id, p_a, final_decision, decision_path, review_label, vlm, in_tumor, rule_override, counted FROM detections"
        ))}
        columns = {c[1] for c in conn.execute(text("PRAGMA table_xinfo(detections)"))}
    for rid, _, _, _, p_a, final_decision, decision_path, review_label in V5_ROWS:
        r = got[rid]
        assert (r.p_a, r.final_decision, r.decision_path, r.review_label) == (p_a, final_decision, decision_path, review_label), rid
        assert r.vlm is None and r.in_tumor is None and not r.rule_override
        assert bool(r.counted) is is_counted(review_label, final_decision, None)
    assert not columns & {"det_conf", "ver_conf", "label", "label_source", "medgemma_verdict", "medgemma_rationale",
                          "medgemma_confidence", "crop_uri", "crop_orig_uri"}

    run(engine, command.downgrade, "0015_hotspot_v6_fields")
    with engine.connect() as conn:
        back = {r.id: r for r in conn.execute(text("SELECT id, det_conf, label, label_source FROM detections"))}
    assert (back["m_0001"].label, back["m_0001"].label_source) == ("mitosis", "model")
    assert (back["m_0004"].label, back["m_0004"].label_source) == ("not_mitosis", "pathologist")
    assert back["m_0003"].label == "unreviewed"
    engine.dispose()


